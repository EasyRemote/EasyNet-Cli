// EasyNet CLI — canonical remote invocation adapter
// ===================================================
//
// File: src/daemon/invocation/routing/remote_invoke.rs
// Description: Projects CLI/A2A/EAL remote targets into a complete,
//              descriptor-bound `InvokeRequest`, signs that request with the
//              caller owner, and submits it to the local daemon's canonical
//              `Invocation::invoke` endpoint.
//
// Wire shape
// ----------
// 1. Caller passes `(ability_ura, args, node_ura)`. `node_ura` must
//    be a canonical Axon Device or Hub URA; non-canonical inputs
//    surface as a typed error before any IPC.
// 2. The helper dials the local daemon's UDS-bound gRPC
//    `Invocation` server (default `~/.easynet/daemon.sock`).
// 3. It sends the actual ability/function, opaque arguments, complete signed
//    envelope, descriptor binding, content envelope, metadata, and deadline
//    in one `InvokeRequest`. Routing may change transport hops but never
//    projects these fields into an inner wrapper payload.
//
// Feature gating
// --------------
// `axon-pb` feature gates the entire module. Production builds run
// with `axon-pb` on; minimal builds (no daemon transport) can drop
// the cross-hub bridge along with the rest of the gRPC stack.
//
// Author: Silan.Hu <silan.hu@u.nus.edu>
// Copyright (c) 2026 EasyNet. All rights reserved.

